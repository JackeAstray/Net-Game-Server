    private static string CppType(string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => "bool",
            FieldKind.Int32 => "int32_t",
            FieldKind.Int64 => "int64_t",
            FieldKind.Float => "float",
            FieldKind.String => "std::string",
            FieldKind.Bytes => "std::vector<uint8_t>",
            FieldKind.List => $"std::vector<{CppType(TypeHelpers.InnerOf(type), protocols)}>",
            FieldKind.Map => CppMapType(type, protocols),
            FieldKind.Struct => type,
            _ => "std::string",
        };
    }

    private static string CppMapType(string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        return $"std::map<{CppType(k, protocols)}, {CppType(v, protocols)}>";
    }

    private static int MemberCount(string structName, List<ProtocolModel> protocols)
    {
        var st = ClientModel.FindStruct(protocols, structName);
        return st?.Fields.Count ?? 0;
    }

    private static string CppDefault(string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => " = false",
            FieldKind.Int32 => " = 0",
            FieldKind.Int64 => " = 0",
            FieldKind.Float => " = 0.0f",
            _ => "",
        };
    }

    private static string CppWrite(string field, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"w.WriteBool({field});",
            FieldKind.Int32 => $"w.WriteI32({field});",
            FieldKind.Int64 => $"w.WriteI64({field});",
            FieldKind.Float => $"w.WriteFloat({field});",
            FieldKind.String => $"w.WriteString({field});",
            FieldKind.Bytes => $"w.WriteBytes({field});",
            FieldKind.List => CppWriteList(field, TypeHelpers.InnerOf(type), protocols),
            FieldKind.Map => CppWriteMap(field, type, protocols),
            FieldKind.Struct => $"w.WriteHeader({MemberCount(type, protocols)}); {field}.WriteBody(w);",
            _ => "",
        };
    }

    private static string CppWriteList(string field, string inner, List<ProtocolModel> protocols)
    {
        string elem = TypeHelpers.KindOf(inner, protocols) switch
        {
            FieldKind.Bool => "w.WriteBool(it);",
            FieldKind.Int32 => "w.WriteI32(it);",
            FieldKind.Int64 => "w.WriteI64(it);",
            FieldKind.Float => "w.WriteFloat(it);",
            FieldKind.String => "w.WriteString(it);",
            FieldKind.Bytes => "w.WriteBytes(it);",
            FieldKind.Struct => $"w.WriteHeader({MemberCount(inner, protocols)}); it.WriteBody(w);",
            _ => "",
        };
        return $"w.WriteCount((int32_t){field}.size()); for (const auto& it : {field}) {{ {elem} }}";
    }

    private static string CppWriteMap(string field, string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        string key = CppWriteMapItem("kv.first", k, protocols);
        string val = CppWriteMapItem("kv.second", v, protocols);
        return $"w.WriteCount((int32_t){field}.size()); for (const auto& kv : {field}) {{ {key} {val} }}";
    }

    private static string CppWriteMapItem(string expr, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"w.WriteBool({expr});",
            FieldKind.Int32 => $"w.WriteI32({expr});",
            FieldKind.Int64 => $"w.WriteI64({expr});",
            FieldKind.Float => $"w.WriteFloat({expr});",
            FieldKind.String => $"w.WriteString({expr});",
            FieldKind.Bytes => $"w.WriteBytes({expr});",
            FieldKind.Struct => $"w.WriteHeader({MemberCount(type, protocols)}); {expr}.WriteBody(w);",
            _ => "",
        };
    }

    private static string CppRead(string field, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"{field} = r.ReadBool();",
            FieldKind.Int32 => $"{field} = r.ReadI32();",
            FieldKind.Int64 => $"{field} = r.ReadI64();",
            FieldKind.Float => $"{field} = r.ReadFloat();",
            FieldKind.String => $"{field} = r.ReadString();",
            FieldKind.Bytes => $"{field} = r.ReadBytes();",
            FieldKind.List => CppReadList(field, TypeHelpers.InnerOf(type), protocols),
            FieldKind.Map => CppReadMap(field, type, protocols),
            FieldKind.Struct => $"r.SkipHeader(); {field}.ReadBody(r);",
            _ => "",
        };
    }

    private static string CppReadList(string field, string inner, List<ProtocolModel> protocols)
    {
        string elem = TypeHelpers.KindOf(inner, protocols) switch
        {
            FieldKind.Bool => "bool _e = r.ReadBool();",
            FieldKind.Int32 => "int32_t _e = r.ReadI32();",
            FieldKind.Int64 => "int64_t _e = r.ReadI64();",
            FieldKind.Float => "float _e = r.ReadFloat();",
            FieldKind.String => "std::string _e = r.ReadString();",
            FieldKind.Bytes => "std::vector<uint8_t> _e = r.ReadBytes();",
            FieldKind.Struct => $"{inner} _e; r.SkipHeader(); _e.ReadBody(r);",
            _ => "",
        };
        return $"int32_t _n = r.ReadCount(); {field}.clear(); {field}.reserve((size_t)_n); for (int32_t _i = 0; _i < _n; ++_i) {{ {elem} {field}.push_back(_e); }}";
    }

    private static string CppReadMap(string field, string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        string key = CppReadMapPart("_k", k, protocols);
        string val = CppReadMapPart("_v", v, protocols);
        return $"int32_t _n = r.ReadCount(); {field}.clear(); for (int32_t _i = 0; _i < _n; ++_i) {{ {key} {val} {field}[_k] = _v; }}";
    }

    private static string CppReadMapPart(string varName, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"bool {varName} = r.ReadBool();",
            FieldKind.Int32 => $"int32_t {varName} = r.ReadI32();",
            FieldKind.Int64 => $"int64_t {varName} = r.ReadI64();",
            FieldKind.Float => $"float {varName} = r.ReadFloat();",
            FieldKind.String => $"std::string {varName} = r.ReadString();",
            FieldKind.Bytes => $"std::vector<uint8_t> {varName} = r.ReadBytes();",
            FieldKind.Struct => $"{type} {varName}; r.SkipHeader(); {varName}.ReadBody(r);",
            _ => $"int32_t {varName} = r.ReadI32();",
        };
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder(name.Length + 2);
        foreach (var ch in name)
        {
            if (char.IsLetterOrDigit(ch)) sb.Append(ch);
            else sb.Append('_');
        }
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

