    private static string BuildMessagesH(List<ProtocolModel> protocols)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 ClientGen 生成，请勿手动修改。");
        sb.AppendLine("#pragma once");
        sb.AppendLine("// 客户端消息定义（与服务器 Framework.Protocol.Generated 二进制兼容，MemoryPack 格式）。");
        sb.AppendLine("#include <cstdint>");
        sb.AppendLine("#include <map>");
        sb.AppendLine("#include <string>");
        sb.AppendLine("#include <vector>");
        sb.AppendLine("#include \"MemoryPack.h\"");
        sb.AppendLine();
        sb.AppendLine("namespace ClientProtocol");
        sb.AppendLine("{");

        // 结构体按依赖拓扑排序（被引用的先输出）
        foreach (var s in TopoSortStructs(protocols))
        {
            AppendStruct(sb, s, protocols);
        }

        foreach (var proto in protocols)
        {
            foreach (var msg in proto.Messages)
            {
                AppendMessage(sb, msg, protocols);
            }
        }

        // 消息 ID 常量（<Name>MsgId 避免与结构体同名冲突）
        sb.AppendLine("    /// <summary>消息 ID 常量。</summary>");
        foreach (var proto in protocols)
        {
            foreach (var msg in proto.Messages)
            {
                sb.AppendLine($"    inline constexpr int32_t {Sanitize(msg.Name)}MsgId = {msg.Id};");
            }
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static IEnumerable<string> StructRefs(string type, List<ProtocolModel> protocols)
    {
        var kind = TypeHelpers.KindOf(type, protocols);
        if (kind == FieldKind.Struct)
        {
            yield return type;
        }
        else if (kind == FieldKind.List)
        {
            foreach (var r in StructRefs(TypeHelpers.InnerOf(type), protocols)) yield return r;
        }
        else if (kind == FieldKind.Map)
        {
            var (k, v) = TypeHelpers.MapPartsOf(type);
            foreach (var r in StructRefs(k, protocols)) yield return r;
            foreach (var r in StructRefs(v, protocols)) yield return r;
        }
    }

    private static List<StructModel> TopoSortStructs(List<ProtocolModel> protocols)
    {
        var all = protocols.SelectMany(p => p.Structs).ToList();
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var result = new List<StructModel>();
        int guard = 0;
        while (result.Count < all.Count && guard++ < all.Count + 1)
        {
            bool added = false;
            foreach (var s in all)
            {
                if (emitted.Contains(s.Name)) continue;
                bool ready = s.Fields.All(f => StructRefs(f.Type, protocols).All(emitted.Contains));
                if (ready)
                {
                    result.Add(s);
                    emitted.Add(s.Name);
                    added = true;
                }
            }
            if (!added) break; // 循环引用（.def 不应出现）
        }
        // 兜底：仍未输出的结构体追加到末尾（避免漏掉）
        foreach (var s in all)
        {
            if (!emitted.Contains(s.Name)) result.Add(s);
        }
        return result;
    }

    private static void AppendStruct(StringBuilder sb, StructModel s, List<ProtocolModel> protocols)
    {
        sb.AppendLine($"/// <summary>结构体 {s.Name}（{s.Fields.Count} 个成员）。</summary>");
        sb.AppendLine($"struct {s.Name}");
        sb.AppendLine("{");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"    {CppType(f.Type, protocols)} {f.Name}{CppDefault(f.Type, protocols)};");
        }
        sb.AppendLine();
        sb.AppendLine("    /// <summary>写入成员数据（不含对象头字节；直接结构体字段会写入自身对象头）。</summary>");
        sb.AppendLine("    void WriteBody(mp::Writer& w) const");
        sb.AppendLine("    {");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"        {CppWrite(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>读取成员数据（不含对象头）。</summary>");
        sb.AppendLine("    void ReadBody(mp::Reader& r)");
        sb.AppendLine("    {");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"        {CppRead(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine("};");
        sb.AppendLine();
    }

    private static void AppendMessage(StringBuilder sb, MessageModel msg, List<ProtocolModel> protocols)
    {
        sb.AppendLine($"/// <summary>{msg.Id} {msg.Name} -> {msg.Target}（服务器目标 {msg.Target}）。</summary>");
        sb.AppendLine($"struct {msg.Name}");
        sb.AppendLine("{");
        sb.AppendLine($"    static constexpr int32_t MsgId = {msg.Id};");
        sb.AppendLine($"    static constexpr const char* Target = \"{msg.Target}\";");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"    {CppType(f.Type, protocols)} {f.Name}{CppDefault(f.Type, protocols)};");
        }
        sb.AppendLine();
        sb.AppendLine("    /// <summary>序列化为完整负载（对象头 + 成员数据），不含帧头。</summary>");
        sb.AppendLine("    std::vector<uint8_t> Serialize() const");
        sb.AppendLine("    {");
        sb.AppendLine("        mp::Writer w;");
        sb.AppendLine($"        w.WriteHeader({msg.Fields.Count});");
        sb.AppendLine("        WriteBody(w);");
        sb.AppendLine("        return w.Take();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    void WriteBody(mp::Writer& w) const");
        sb.AppendLine("    {");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"        {CppWrite(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    void ReadBody(mp::Reader& r)");
        sb.AppendLine("    {");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"        {CppRead(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>从负载反序列化（跳过对象头后读成员数据）。</summary>");
        sb.AppendLine($"    static {msg.Name} Deserialize(const uint8_t* data, size_t size)");
        sb.AppendLine("    {");
        sb.AppendLine("        mp::Reader r(data, size);");
        sb.AppendLine("        r.SkipHeader();");
        sb.AppendLine($"        {msg.Name} m;");
        sb.AppendLine("        m.ReadBody(r);");
        sb.AppendLine("        return m;");
        sb.AppendLine("    }");
        sb.AppendLine("};");
        sb.AppendLine();
    }

