    private const string CodecTemplate = """
// <auto-generated> 由 ClientGen 生成，请勿手动修改。
// 与服务器 MemoryPack 二进制格式逐字节兼容的零依赖编解码器。
// 格式要点（经真实 MemoryPack 输出实证）：
//   - 每个类对象（根对象 / 直接结构体字段 / 集合元素 / map 值）：1 字节对象头 = 成员数
//   - 数值：定长小端（bool=1 字节 / int32=4 / int64=8 / float=4 / double=8）
//   - 字符串：int32(~utf8len) + int32(utf16len) + UTF-8 字节；空串 = int32(0)
//   - byte[]：int32(len) + 字节
//   - List/Map：int32(count) + 元素（结构体元素带对象头）
#nullable enable
using System;
using System.Collections.Generic;
using System.Text;

namespace ClientProtocol
{
    /// <summary>帧载荷（不含帧头）的抽象。</summary>
    public interface IMessage
    {
        int MessageId { get; }
        byte[] Serialize();
    }

    /// <summary>MemoryPack 兼容二进制写入器。</summary>
    public sealed class MpWriter
    {
        private readonly List<byte> buf = new List<byte>();

        public void WriteByte(byte v) => buf.Add(v);
        public void WriteHeader(int memberCount) => buf.Add((byte)memberCount);
        public void WriteBool(bool v) => buf.Add(v ? (byte)1 : (byte)0);
        public void WriteI32(int v)
        {
            buf.Add((byte)v); buf.Add((byte)(v >> 8)); buf.Add((byte)(v >> 16)); buf.Add((byte)(v >> 24));
        }
        public void WriteI64(long v)
        {
            buf.Add((byte)v); buf.Add((byte)(v >> 8)); buf.Add((byte)(v >> 16)); buf.Add((byte)(v >> 24));
            buf.Add((byte)(v >> 32)); buf.Add((byte)(v >> 40)); buf.Add((byte)(v >> 48)); buf.Add((byte)(v >> 56));
        }
        public void WriteFloat(float v) => WriteI32(BitConverter.SingleToInt32Bits(v));
        public void WriteDouble(double v) => WriteI64(BitConverter.DoubleToInt64Bits(v));

        public void WriteString(string? s)
        {
            if (string.IsNullOrEmpty(s)) { WriteI32(0); return; }
            byte[] utf8 = Encoding.UTF8.GetBytes(s);
            WriteI32(~utf8.Length);
            WriteI32(s.Length); // UTF-16 长度
            buf.AddRange(utf8);
        }

        public void WriteBytes(byte[]? b)
        {
            if (b == null) { WriteI32(0); return; }
            WriteI32(b.Length);
            buf.AddRange(b);
        }

        public void WriteCount(int n) => WriteI32(n);

        public byte[] ToArray() => buf.ToArray();
    }

    /// <summary>MemoryPack 兼容二进制读取器。</summary>
    public sealed class MpReader
    {
        private readonly byte[] data;
        private int pos;

        public MpReader(byte[] data) { this.data = data; pos = 0; }

        /// <summary>跳过对象头字节（假定非空对象）。</summary>
        public void SkipHeader() { pos++; }

        public bool ReadBool() => data[pos++] != 0;

        public int ReadI32()
        {
            int v = data[pos] | (data[pos + 1] << 8) | (data[pos + 2] << 16) | (data[pos + 3] << 24);
            pos += 4;
            return v;
        }

        public long ReadI64()
        {
            long lo = (uint)ReadI32();
            long hi = (uint)ReadI32();
            return lo | (hi << 32);
        }

        public float ReadFloat() => BitConverter.Int32BitsToSingle(ReadI32());
        public double ReadDouble() => BitConverter.Int64BitsToDouble(ReadI64());

        public string ReadString()
        {
            int v = ReadI32();
            if (v == 0) return "";
            int utf8Len = ~v;
            ReadI32(); // UTF-16 长度（客户端只需 UTF-8 字节）
            string s = Encoding.UTF8.GetString(data, pos, utf8Len);
            pos += utf8Len;
            return s;
        }

        public byte[] ReadBytes()
        {
            int n = ReadI32();
            if (n == 0) return Array.Empty<byte>();
            var b = new byte[n];
            Array.Copy(data, pos, b, 0, n);
            pos += n;
            return b;
        }

        public int ReadCount() => ReadI32();
    }
}
""";

    private const string NetClientTemplate = """
// <auto-generated> 由 ClientGen 生成，请勿手动修改。
// 客户端 TCP 网络层：帧格式与服务器一致 [TotalLength(4)][MsgId(4)][Payload]
//   - TotalLength = 4 + Payload.Length（小端 int32）
// 用法：
//   Unity：在 MonoBehaviour.Update() 中每帧调用 client.Poll(OnMessage)
//   纯 .NET：循环调用 client.Poll(OnMessage)（或后台线程）
#nullable enable
using System;
using System.Net.Sockets;

namespace ClientProtocol
{
    /// <summary>
    /// 与 Net-Game-Server Gateway 通信的轻量 TCP 客户端（零依赖，可直接导入 Unity / 任意 C#）。
    /// 发送用 MemoryPack 兼容编解码（MpWriter/MpReader），或直接传 JSON 负载（服务器 jsonFallback 接受）。
    /// </summary>
    public sealed class NetClient : IDisposable
    {
        private TcpClient? tcp;
        private NetworkStream? stream;
        private byte[] recv = new byte[16384];
        private int recvLen;

        public bool Connected => tcp != null && tcp.Connected && stream != null;

        /// <summary>连接 Gateway（阻塞）。</summary>
        public void Connect(string host, int port)
        {
            tcp = new TcpClient();
            tcp.Connect(host, port);
            stream = tcp.GetStream();
        }

        /// <summary>断开连接。</summary>
        public void Disconnect()
        {
            try { stream?.Close(); } catch { }
            try { tcp?.Close(); } catch { }
            stream = null; tcp = null; recvLen = 0;
        }

        /// <summary>发送一条完整负载（自动加 [TotalLength][MsgId] 帧头）。</summary>
        public void Send(int msgId, byte[] payload)
        {
            if (stream == null) throw new InvalidOperationException("NetClient 未连接");
            int inner = 4 + payload.Length;
            var frame = new byte[4 + inner];
            WriteInt32LE(frame, 0, inner);
            WriteInt32LE(frame, 4, msgId);
            Buffer.BlockCopy(payload, 0, frame, 8, payload.Length);
            stream.Write(frame, 0, frame.Length);
        }

        /// <summary>发送一个消息对象（用 MemoryPack 兼容序列化）。</summary>
        public void Send(IMessage message) => Send(message.MessageId, message.Serialize());

        /// <summary>发送 JSON 文本负载（服务器 jsonFallback 自动识别，字段名 PascalCase）。</summary>
        public void SendJson(int msgId, string jsonPayload)
        {
            var bytes = System.Text.Encoding.UTF8.GetBytes(jsonPayload);
            Send(msgId, bytes);
        }

        /// <summary>
        /// 非阻塞接收泵：读取 socket 已到达数据，解析完整帧后回调 onMessage(msgId, payload)。
        /// 必须在连接存续期间周期性调用（Unity Update / 主循环）。
        /// </summary>
        public void Poll(Action<int, byte[]> onMessage)
        {
            if (stream == null) return;

            // 1) 排空 socket（不足则扩容）
            while (stream.DataAvailable)
            {
                if (recvLen == recv.Length)
                {
                    var bigger = new byte[recv.Length * 2];
                    Buffer.BlockCopy(recv, 0, bigger, 0, recvLen);
                    recv = bigger;
                }
                int n = stream.Read(recv, recvLen, recv.Length - recvLen);
                if (n <= 0) { Disconnect(); return; }
                recvLen += n;
            }

            // 2) 解析完整帧 [TotalLength(4)][MsgId(4)][Payload]
            int pos = 0;
            while (true)
            {
                if (recvLen - pos < 4) break;
                int total = ReadInt32LE(recv, pos);
                if (total < 4 || recvLen - pos - 4 < total) break; // 不完整帧
                int msgId = ReadInt32LE(recv, pos + 4);
                var payload = new byte[total - 4];
                Buffer.BlockCopy(recv, pos + 8, payload, 0, total - 4);
                onMessage(msgId, payload);
                pos += 4 + total;
            }

            // 3) 压缩剩余字节
            if (pos > 0 && pos < recvLen)
            {
                Buffer.BlockCopy(recv, pos, recv, 0, recvLen - pos);
                recvLen -= pos;
            }
            else if (pos > 0)
            {
                recvLen = 0;
            }
        }

        public void Dispose() => Disconnect();

        private static void WriteInt32LE(byte[] dst, int offset, int v)
        {
            dst[offset] = (byte)v;
            dst[offset + 1] = (byte)(v >> 8);
            dst[offset + 2] = (byte)(v >> 16);
            dst[offset + 3] = (byte)(v >> 24);
        }

        private static int ReadInt32LE(byte[] src, int offset) =>
            src[offset] | (src[offset + 1] << 8) | (src[offset + 2] << 16) | (src[offset + 3] << 24);
    }
}
""";

