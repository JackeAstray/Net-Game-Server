    private const string Ns = "ClientProtocol";

    public static string GenerateMessageIds(List<ProtocolModel> protocols)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 ClientGen 生成，请勿手动修改。");
        sb.AppendLine($"namespace {Ns};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>全协议消息 ID 常量（与服务器 Framework.Protocol.Generated.MessageIds 一致）。</summary>");
        sb.AppendLine("public static class MessageIds");
        sb.AppendLine("{");
        foreach (var proto in protocols)
        {
            foreach (var msg in proto.Messages)
            {
                sb.AppendLine($"    /// <summary>{msg.Id} {msg.Name} -> {msg.Target}</summary>");
                sb.AppendLine($"    public const int {Sanitize(msg.Name)} = {msg.Id};");
            }
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string GenerateCodec() => CodecTemplate;

    public static string GenerateMessages(List<ProtocolModel> protocols)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 ClientGen 生成，请勿手动修改。");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Ns};");
        sb.AppendLine();

        // 结构体
        foreach (var proto in protocols)
        {
            foreach (var s in proto.Structs)
            {
                AppendStruct(sb, s, protocols);
            }
        }

        // 消息
        foreach (var proto in protocols)
        {
            foreach (var msg in proto.Messages)
            {
                AppendMessage(sb, msg, protocols);
            }
        }
        return sb.ToString();
    }

