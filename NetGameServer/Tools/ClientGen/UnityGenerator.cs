    // ---------- helpers ----------

    private static void AppendStruct(StringBuilder sb, StructModel s, List<ProtocolModel> protocols)
    {
        sb.AppendLine($"/// <summary>结构体 {s.Name}（{s.Fields.Count} 个成员）。</summary>");
        sb.AppendLine($"public sealed class {s.Name}");
        sb.AppendLine("{");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"    public {CsType(f.Type, protocols)} {f.Name} = {DefaultExpr(f.Type, protocols)};");
        }
        sb.AppendLine();
        sb.AppendLine("    /// <summary>写入成员数据（不含对象头字节；直接结构体字段会写入自身对象头）。</summary>");
        sb.AppendLine("    public void WriteBody(MpWriter w)");
        sb.AppendLine("    {");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"        {WriteExpr(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>读取成员数据（不含对象头字节）。</summary>");
        sb.AppendLine("    public void ReadBody(MpReader r)");
        sb.AppendLine("    {");
        foreach (var f in s.Fields)
        {
            sb.AppendLine($"        {ReadExpr(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void AppendMessage(StringBuilder sb, MessageModel msg, List<ProtocolModel> protocols)
    {
        sb.AppendLine($"/// <summary>{msg.Id} {msg.Name} -> {msg.Target}（服务器目标 {msg.Target}）。</summary>");
        sb.AppendLine($"public sealed class {msg.Name} : IMessage");
        sb.AppendLine("{");
        sb.AppendLine($"    public const int MsgId = {msg.Id};");
        sb.AppendLine($"    public const string Target = \"{msg.Target}\";");
        sb.AppendLine($"    int IMessage.MessageId => MsgId;");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"    public {CsType(f.Type, protocols)} {f.Name} = {DefaultExpr(f.Type, protocols)};");
        }
        sb.AppendLine();
        sb.AppendLine("    /// <summary>序列化为完整负载（对象头字节 + 成员数据），不含帧头。</summary>");
        sb.AppendLine("    public byte[] Serialize()");
        sb.AppendLine("    {");
        sb.AppendLine($"        var w = new MpWriter(); w.WriteHeader({msg.Fields.Count}); WriteBody(w); return w.ToArray();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>写入成员数据（不含对象头字节）。</summary>");
        sb.AppendLine("    public void WriteBody(MpWriter w)");
        sb.AppendLine("    {");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"        {WriteExpr(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>读取成员数据（不含对象头字节）。</summary>");
        sb.AppendLine("    public void ReadBody(MpReader r)");
        sb.AppendLine("    {");
        foreach (var f in msg.Fields)
        {
            sb.AppendLine($"        {ReadExpr(f.Name, f.Type, protocols)}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>从负载反序列化（跳过对象头字节后读成员数据）。</summary>");
        sb.AppendLine("    public static " + msg.Name + " Deserialize(byte[] data)");
        sb.AppendLine("    {");
        sb.AppendLine("        var r = new MpReader(data); r.SkipHeader();");
        sb.AppendLine($"        var m = new {msg.Name}(); m.ReadBody(r); return m;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    // ---------- type mapping ----------

    public static string CsType(string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => "bool",
            FieldKind.Int32 => "int",
            FieldKind.Int64 => "long",
            FieldKind.Float => "float",
            FieldKind.String => "string",
            FieldKind.Bytes => "byte[]",
            FieldKind.List => $"List<{CsType(TypeHelpers.InnerOf(type), protocols)}>",
            FieldKind.Map => MapType(type, protocols),
            FieldKind.Struct => type,
            _ => type,
        };
    }

    private static string MapType(string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        return $"Dictionary<{CsType(k, protocols)}, {CsType(v, protocols)}>";
    }

    private static int MemberCount(string structName, List<ProtocolModel> protocols)
    {
        var st = ClientModel.FindStruct(protocols, structName);
        return st?.Fields.Count ?? 0;
    }

    private static string DefaultExpr(string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => "false",
            FieldKind.Int32 => "0",
            FieldKind.Int64 => "0L",
            FieldKind.Float => "0f",
            FieldKind.String => "\"\"",
            FieldKind.Bytes => "Array.Empty<byte>()",
            FieldKind.List => $"new List<{CsType(TypeHelpers.InnerOf(type), protocols)}>()",
            FieldKind.Map => $"new {MapType(type, protocols)}()",
            FieldKind.Struct => $"new {type}()",
            _ => "\"\"",
        };
    }

    private static string WriteExpr(string field, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"w.WriteBool({field});",
            FieldKind.Int32 => $"w.WriteI32({field});",
            FieldKind.Int64 => $"w.WriteI64({field});",
            FieldKind.Float => $"w.WriteFloat({field});",
            FieldKind.String => $"w.WriteString({field});",
            FieldKind.Bytes => $"w.WriteBytes({field});",
            FieldKind.List => WriteListExpr(field, TypeHelpers.InnerOf(type), protocols),
            FieldKind.Map => WriteMapExpr(field, type, protocols),
            FieldKind.Struct => $"w.WriteHeader({MemberCount(type, protocols)}); {field}.WriteBody(w);",
            _ => "",
        };
    }

    private static string WriteListExpr(string field, string inner, List<ProtocolModel> protocols)
    {
        string elem = TypeHelpers.KindOf(inner, protocols) switch
        {
            FieldKind.Bool => "w.WriteBool(it);",
            FieldKind.Int32 => "w.WriteI32(it);",
            FieldKind.Int64 => "w.WriteI64(it);",
            FieldKind.Float => "w.WriteFloat(it);",
            FieldKind.String => "w.WriteString(it);",
            FieldKind.Bytes => "w.WriteBytes(it);",
            FieldKind.Struct => $"w.WriteHeader({MemberCount(inner, protocols)}); it.WriteBody(w);",
            FieldKind.List => throw new InvalidOperationException("嵌套 list 暂不支持: " + inner),
            FieldKind.Map => throw new InvalidOperationException("list:map 暂不支持: " + inner),
            _ => "",
        };
        return $"w.WriteCount({field}.Count); foreach (var it in {field}) {{ {elem} }}";
    }

    private static string WriteMapExpr(string field, string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        string key = WriteMapItem("kv.Key", k, protocols);
        string val = WriteMapItem("kv.Value", v, protocols);
        return $"w.WriteCount({field}.Count); foreach (var kv in {field}) {{ {key} {val} }}";
    }

    private static string WriteMapItem(string expr, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"w.WriteBool({expr});",
            FieldKind.Int32 => $"w.WriteI32({expr});",
            FieldKind.Int64 => $"w.WriteI64({expr});",
            FieldKind.Float => $"w.WriteFloat({expr});",
            FieldKind.String => $"w.WriteString({expr});",
            FieldKind.Bytes => $"w.WriteBytes({expr});",
            FieldKind.Struct => $"w.WriteHeader({MemberCount(type, protocols)}); {expr}.WriteBody(w);",
            _ => "",
        };
    }

    private static string ReadExpr(string field, string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => $"{field} = r.ReadBool();",
            FieldKind.Int32 => $"{field} = r.ReadI32();",
            FieldKind.Int64 => $"{field} = r.ReadI64();",
            FieldKind.Float => $"{field} = r.ReadFloat();",
            FieldKind.String => $"{field} = r.ReadString();",
            FieldKind.Bytes => $"{field} = r.ReadBytes();",
            FieldKind.List => ReadListExpr(field, TypeHelpers.InnerOf(type), protocols),
            FieldKind.Map => ReadMapExpr(field, type, protocols),
            FieldKind.Struct => $"r.SkipHeader(); {field}.ReadBody(r);",
            _ => "",
        };
    }

    private static string ReadListExpr(string field, string inner, List<ProtocolModel> protocols)
    {
        string elem = TypeHelpers.KindOf(inner, protocols) switch
        {
            FieldKind.Bool => "var _e = r.ReadBool();",
            FieldKind.Int32 => "var _e = r.ReadI32();",
            FieldKind.Int64 => "var _e = r.ReadI64();",
            FieldKind.Float => "var _e = r.ReadFloat();",
            FieldKind.String => "var _e = r.ReadString();",
            FieldKind.Bytes => "var _e = r.ReadBytes();",
            FieldKind.Struct => $"var _e = new {inner}(); r.SkipHeader(); _e.ReadBody(r);",
            _ => "",
        };
        return $"int _n = r.ReadCount(); {field} = new List<{CsType(inner, protocols)}>(); for (int _i = 0; _i < _n; _i++) {{ {elem} {field}.Add(_e); }}";
    }

    private static string ReadMapExpr(string field, string type, List<ProtocolModel> protocols)
    {
        var (k, v) = TypeHelpers.MapPartsOf(type);
        string key = $"var _k = {ReadValueExpr(k, protocols)};";
        string val = $"var _v = {ReadValueExpr(v, protocols)};";
        return $"int _n = r.ReadCount(); {field} = new {MapType(type, protocols)}(); for (int _i = 0; _i < _n; _i++) {{ {key} {val} {field}[_k] = _v; }}";
    }

    private static string ReadValueExpr(string type, List<ProtocolModel> protocols)
    {
        return TypeHelpers.KindOf(type, protocols) switch
        {
            FieldKind.Bool => "r.ReadBool()",
            FieldKind.Int32 => "r.ReadI32()",
            FieldKind.Int64 => "r.ReadI64()",
            FieldKind.Float => "r.ReadFloat()",
            FieldKind.String => "r.ReadString()",
            FieldKind.Bytes => "r.ReadBytes()",
            FieldKind.Struct => $"(() => {{ var _s = new {type}(); r.SkipHeader(); _s.ReadBody(r); return _s; }})()",
            _ => "r.ReadI32()",
        };
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder(name.Length + 2);
        foreach (var ch in name)
        {
            if (char.IsLetterOrDigit(ch)) sb.Append(ch);
            else sb.Append('_');
        }
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

